import SwiftUI

// UI language is independent of DSP configuration and survives app launches.
enum AppLanguage {
    static let key = "interfaceLanguage"
    static var isChinese: Bool { UserDefaults.standard.string(forKey: key) == "zh-Hans" }
}

func L(_ text: String) -> String {
    guard AppLanguage.isChinese else { return text }
    if let translated = translations[text] { return translated }
    if text.hasPrefix("Listening · ") { return text.replacingOccurrences(of:"Listening · ",with:"已就绪 · ") }
    if text.hasPrefix("Processing · ") { return text.replacingOccurrences(of:"Processing · ",with:"正在处理 · ") }
    if text.hasPrefix("FIR ready · ") { return text.replacingOccurrences(of: "FIR ready · ", with: "FIR 已就绪 · ").replacingOccurrences(of: " taps", with: " 抽头") }
    if text.hasPrefix("Rendered ") { return text.replacingOccurrences(of: "Rendered ", with: "已渲染 ").replacingOccurrences(of: " frames · peak ", with: " 帧 · 峰值 ") }
    if text.hasPrefix("IR sample-rate mismatch: ") { return text.replacingOccurrences(of:"IR sample-rate mismatch: ",with:"IR 采样率不匹配：").replacingOccurrences(of:" Hz versus ",with:" Hz，当前为 ").replacingOccurrences(of:" Hz; explicitly convert the WAV before import",with:" Hz；请先转换 WAV 再导入") }
    if text.hasPrefix("PEQ band ") { return text.replacingOccurrences(of:"PEQ band ",with:"PEQ 频段 ").replacingOccurrences(of:" requires exactly frequency_hz, q, gain_db without null values",with:" 必须且只能包含 frequency_hz、q、gain_db，不能使用空值").replacingOccurrences(of:" has frequency, Q, or gain outside the supported range",with:" 的频率、Q 或增益超出支持范围") }
    if text.hasPrefix("Invalid WAV: ") {return "无效 WAV："+L(String(text.dropFirst(13)))}
    return text
}

